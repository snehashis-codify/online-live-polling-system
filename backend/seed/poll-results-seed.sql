--
-- Poll 2 "Best JS framework"  (anonymous, 5 responses, respondent_id NULL)
--   Q1 radio  React 3 | Vue 1 | Svelte 1 | Angular 0
--
-- Poll 3 "Lunch menu"  (draft, 0 responses)
--   Q1 radio  Pizza 0 | Biryani 0
--
-- Traps this data is built to catch:
--   * Pondicherry / Angular / all of Poll 3 have ZERO answers. If your query
--     starts FROM answers, those options disappear. Start from options and
--     LEFT JOIN answers instead.
--   * Poll 2 shares no IDs with Poll 1. If its options show up in Poll 1's
